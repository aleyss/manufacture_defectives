"""
Industrial Copilot Engine: Connects Vision outputs to SLM reasoning.
Supports: Local Ollama (Llama 3.2 / Qwen 2.5), Cloud API, or Built-in Expert Fallback.
"""

import json
import urllib.request
from knowledge_base import PCB_DEFECT_KB

def get_installed_ollama_model():
    """
    Auto-detects the active model installed in local Ollama.
    Prefers llama3.2:latest, llama3.2, or the first available model.
    """
    try:
        req = urllib.request.Request("http://localhost:11434/api/tags")
        with urllib.request.urlopen(req, timeout=3) as resp:
            data = json.loads(resp.read().decode("utf-8"))
            installed = [m['name'] for m in data.get('models', [])]
            for candidate in ["llama3.2:latest", "llama3.2", "llama3.2:3b", "qwen2.5:3b", "qwen2.5:latest"]:
                if candidate in installed:
                    return candidate
            if installed:
                return installed[0]
    except Exception:
        pass
    return "llama3.2:latest"

def generate_8d_analysis(defect_class: str, confidence: float, bbox: list, model_backend="local_ollama", custom_notes=""):
    """
    Combines YOLO vision outputs with domain knowledge and generates a structured 8D diagnosis.
    Returns: formatted markdown text with clear provenance badge.
    """
    kb = PCB_DEFECT_KB.get(defect_class, {})
    
    # Grounding Context from Knowledge Base
    domain_context = f"""
    Defect: {kb.get('full_name', defect_class)}
    Originating Station: {kb.get('station_of_origin', 'Assembly Line')}
    IPC-A-610 Standards:
      - Class 1: {kb.get('ipc_class_verdict', {}).get('Class 1 (General)')}
      - Class 2: {kb.get('ipc_class_verdict', {}).get('Class 2 (Dedicated)')}
      - Class 3: {kb.get('ipc_class_verdict', {}).get('Class 3 (High Reliability)')}
    Standard Root Causes: {', '.join(kb.get('probable_root_causes', []))}
    Immediate Containment: {kb.get('containment_action')}
    Recommended CAPA: {kb.get('capa_preventive_action')}
    """
    
    prompt = f"""You are a Lead Quality Assurance Engineer in a high-tech PCB manufacturing plant.
An Automated Optical Inspection (AOI) camera powered by YOLO has flagged the following defect:

[AOI VISION METRICS]
- Defect Type: {defect_class} ({kb.get('full_name', defect_class)})
- Detection Confidence: {confidence * 100:.2f}%
- Bounding Box [x1, y1, x2, y2]: {bbox}
- Originating Station: {kb.get('station_of_origin', 'SMT Line')}
- Operator Notes: {custom_notes if custom_notes else 'None provided'}

[STANDARDS & SMT KNOWLEDGE]
{domain_context}

Analyze this incident and generate an official 8D Quality Summary.
Provide your response strictly with these 4 clear sections:
1. 🏷️ IPC-A-610 COMPLIANCE VERDICT (Class 2 and Class 3 assessment)
2. 🔍 ROOT CAUSE INVESTIGATION (Pinpoint exact machine parameter failures)
3. 🚨 OPERATOR CONTAINMENT ACTION (What the line technician must do immediately)
4. 🛡️ CORRECTIVE & PREVENTIVE ACTION (CAPA)
Keep the response crisp and authoritative.
"""

    # If user selected Ollama local SLM
    if model_backend == "local_ollama":
        try:
            model_tag = get_installed_ollama_model()
            payload = json.dumps({
                "model": model_tag,
                "prompt": prompt,
                "stream": False,
                "options": {"temperature": 0.2, "num_predict": 300}
            }).encode("utf-8")
            req = urllib.request.Request(
                "http://localhost:11434/api/generate",
                data=payload,
                headers={"Content-Type": "application/json"}
            )
            with urllib.request.urlopen(req, timeout=35) as response:
                res_data = json.loads(response.read().decode("utf-8"))
                llm_response = res_data.get("response", "").strip()
                if llm_response:
                    badge = f"> 🧠 **Generated by Local SLM (`{model_tag}`)** — Neural Reasoning grounded in IPC-A-610\n\n"
                    return badge + llm_response
        except Exception:
            # Fall through to deterministic synthesis if Ollama is busy/offline
            pass

    # Built-in High-Precision Engineering Synthesis (Fallback / Standalone)
    rule_synthesis = f"""### 🏷️ IPC-A-610 Compliance Verdict
* **Defect Class:** `{defect_class}` — **{kb.get('full_name', defect_class)}**
* **Class 1 (Consumer):** {kb.get('ipc_class_verdict', {}).get('Class 1 (General)', 'Evaluate clearance')}
* **Class 2 (Dedicated Service):** {kb.get('ipc_class_verdict', {}).get('Class 2 (Dedicated)', 'Requires inspection')}
* **Class 3 (High Reliability / Automotive):** {kb.get('ipc_class_verdict', {}).get('Class 3 (High Reliability)', 'CRITICAL REJECT')}

### 🔍 Root Cause Investigation
* **Responsible Station:** {kb.get('station_of_origin', 'Etching / CNC Station')}
* **Identified Failure Mode:** Vision system identified `{defect_class}` with {confidence*100:.1f}% confidence at coordinates `{bbox}`.
* **Primary Hypotheses:**
  1. {kb.get('probable_root_causes', ['Process parameter variation'])[0]}
  2. {kb.get('probable_root_causes', ['Tooling or chemical drift'])[1] if len(kb.get('probable_root_causes', [])) > 1 else 'Process drift'}

### 🚨 Operator Immediate Containment
* **Action:** {kb.get('containment_action', 'Quarantine affected panel lot immediately.')}
* **Disposition:** Hold current batch from entering subsequent assembly stages.

### 🛡️ Corrective & Preventive Action (CAPA)
* **Permanent Fix:** {kb.get('capa_preventive_action', 'Calibrate machine tooling and replenish chemical bath.')}
* **Verification:** Log incident in MES (Manufacturing Execution System) and verify next 3 consecutive panels.
"""
    badge = "> ⚡ **Generated by Industrial Rule Synthesizer** — Zero-Latency IPC-A-610 Deterministic Engine\n\n"
    return badge + rule_synthesis

def answer_technician_question(question: str, defect_class: str, model_backend="local_ollama"):
    """
    Answers live technician follow-up questions.
    Uses Ollama for natural conversational answers or the expert rule engine.
    """
    # Detect if user is asking about a specific defect different from detected defect
    q_lower = question.lower()
    target_class = defect_class
    for c in PCB_DEFECT_KB.keys():
        if c.replace("_", " ") in q_lower or c in q_lower:
            target_class = c
            break

    kb = PCB_DEFECT_KB.get(target_class, {})
    
    # Try Ollama first if selected
    if model_backend == "local_ollama":
        try:
            model_tag = get_installed_ollama_model()
            q_prompt = f"""You are a Lead PCB Quality and Rework Engineer on an active SMT/AOI assembly line.
A technician asks you: "{question}"

Context:
- Primary Defect Under Review: {target_class} ({kb.get('full_name', target_class)})
- Station: {kb.get('station_of_origin', 'SMT Production Line')}
- Relevant IPC-A-610 Criteria: {kb.get('ipc_class_verdict', {})}
- Containment Protocol: {kb.get('containment_action', '')}

Provide a direct, conversational, and authoritative technical response (within 80-120 words).
Explain whether mechanical scraping, trimming, or rework is permissible under IPC-A-610 Class 2 vs Class 3, and give exact actionable instruction.
"""
            payload = json.dumps({
                "model": model_tag,
                "prompt": q_prompt,
                "stream": False,
                "options": {"temperature": 0.2, "num_predict": 140}
            }).encode("utf-8")
            req = urllib.request.Request(
                "http://localhost:11434/api/generate",
                data=payload,
                headers={"Content-Type": "application/json"}
            )
            with urllib.request.urlopen(req, timeout=30) as response:
                res_data = json.loads(response.read().decode("utf-8"))
                llm_response = res_data.get("response", "").strip()
                if llm_response:
                    return f"> 🧠 **Copilot Response (Local Ollama `{model_tag}`):**\n\n" + llm_response
        except Exception:
            pass

    # Expert rule-based response
    specific_advice = {
        "spur": "Under IPC-7721, mechanical trimming of a spur using a precision micro-scalpel under 10x-40x magnification is permissible ONLY for Class 1 and Class 2 if base laminate and trace adhesion remain undamaged. For Class 3 (aerospace/automotive), mechanical scraping of copper is strictly non-conforming and prohibited.",
        "spurious_copper": "Spurious copper flakes must be tested for adhesion. If loose, clean with ultrasonic DI rinse. If bonded, verify whether it encroaches on clearance envelopes (>0.15mm required). If within clearance, board may require laser ablation or be marked for scrap.",
        "mouse_bite": "Measure remaining conductor width with an optical comparator. If conductor loss is <20% for Class 2, board is acceptable without rework. For >20% loss, jumper wire bypass or trace rebuilding is required according to IPC-7721.",
        "open_circuit": "Verify open circuit using flying-probe continuity tester. Trace jumper wire repair is permissible for Class 1 & 2 per IPC-7721 section 4.2.3, but prohibited for Class 3 high-reliability builds.",
        "short": "Check if short is solder bridge (reworkable with flux and desoldering braid / hot air at 315°C) or etched copper webbing (requires micro-machining or panel scrap).",
        "missing_hole": "Missing vias/PTH cannot be manually drilled after plating without risking multi-layer barrel delamination. The panel must be marked as SCRAP."
    }

    defect_guidance = specific_advice.get(
        target_class,
        "Refer to IPC-7711/7721 Rework and Repair of Electronic Assemblies manual."
    )

    return (
        f"> ⚡ **Copilot Response (Industrial Rule Engine):**\n\n"
        f"**Quality Guidance regarding `{target_class}` ({kb.get('full_name', target_class)}):**\n\n"
        f"**Operator Inquiry:** *\"{question}\"*\n\n"
        f"- **Primary Station to verify:** {kb.get('station_of_origin', 'SMT Line')}\n"
        f"- **Standard Protocol:** {kb.get('containment_action')}\n"
        f"- **Technical Assessment:** {defect_guidance}\n"
        f"- **IPC Rule:** IPC-A-610 Class 2 & Class 3 require full trace and clearance integrity before downstream conformal coating or potting."
    )